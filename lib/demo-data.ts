/** Tren aliran kas 6 bulan terakhir (Rp) — pola dari desain. */
export function buildDemoTrend(): TrendBulan[] {
  const masuk = [
    6_500_000, 7_000_000, 7_500_000, 8_000_000, 7_750_000, 7_560_000,
  ];
  const keluar = [
    3_500_000, 4_000_000, 4_500_000, 4_250_000, 3_750_000, 3_250_000,
  ];
  const formatter = new Intl.DateTimeFormat("id-ID", { month: "short" });
  const now = new Date();

  return masuk.map((nilaiMasuk, index) => {
    const tanggal = new Date(now.getFullYear(), now.getMonth() - (5 - index), 1);
    return {
      label: formatter.format(tanggal),
      masuk: nilaiMasuk,
      keluar: keluar[index],
    };
  });
}

