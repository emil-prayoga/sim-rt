function jamHariIni(jam: number, menit: number): string {
  const d = new Date();
  d.setHours(jam, menit, 0, 0);
  return d.toISOString();
}

function jamHariLalu(hariLalu: number, jam: number, menit: number): string {
  const d = new Date();
  d.setDate(d.getDate() - hariLalu);
  d.setHours(jam, menit, 0, 0);
  return d.toISOString();
}

